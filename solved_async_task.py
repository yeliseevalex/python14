# COURIER — СПОЖИВАЧ
# =============================================================================

async def courier(name):
    """
    Courier — Consumer.

    Кур'єр постійно отримує замовлення
    з асинхронної черги.

    Якщо Queue порожня:

        await orders_queue.get()

    автоматично призупинить coroutine.

    Event loop при цьому може виконувати
    інші задачі.
    """

    print(f"[{name}] Почав роботу.")

    try:

        while True:

            # Отримуємо замовлення з Queue.
            #
            # Якщо черга порожня,
            # кур'єр буде чекати.
            order = await orders_queue.get()

            try:

                # Повністю обробляємо замовлення.
                await process_order(
                    order,
                    name
                )

            finally:

                # Повідомляємо Queue,
                # що роботу з цим замовленням завершено.
                #
                # Це необхідно для:
                #
                #     await orders_queue.join()
                orders_queue.task_done()

    except asyncio.CancelledError:

        # Кур'єр може бути скасований системою.
        print(
            f"[{name}] "
            f"Роботу кур'єра скасовано."
        )

        # Передаємо CancelledError далі,
        # щоб Task залишалася скасованою.
        raise


