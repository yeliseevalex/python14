async def deliver_order(order, courier_name):
    """
    Доставляє замовлення клієнту.

    Час доставки випадковий:
    від 1 до 7 секунд.

    Якщо доставка триватиме більше 5 секунд,
    asyncio.wait_for() зовні скасує цю coroutine.
    """

    order_id = order["id"]

    print(
        f"[{courier_name}] "
        f"Замовлення #{order_id}: "
        f"вирушаю до клієнта..."
    )

    # Випадковий час доставки.
    delivery_time = random.uniform(1, 7)

    try:

        # Імітуємо поїздку кур'єра.
        await asyncio.sleep(delivery_time)

    except asyncio.CancelledError:

        # Цей блок виконається,
        # якщо coroutine буде скасована.
        print(
            f"[{courier_name}] "
            f"Замовлення #{order_id}: "
            f"доставку скасовано!"
        )

        # Передаємо CancelledError далі.
        raise

    print(
        f"[{courier_name}] "
        f"Замовлення #{order_id}: "
        f"доставлено клієнту!"
    )


