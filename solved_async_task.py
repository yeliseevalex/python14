# MAIN — ГОЛОВНА COROUTINE
# =============================================================================

async def main():

    print()
    print("=" * 70)
    print("        СИСТЕМУ ДОСТАВКИ ЗАПУЩЕНО")
    print("=" * 70)
    print()

    # =========================================================================
    # СТВОРЮЄМО TASK ДЛЯ DISPATCHER
    # =========================================================================

    # create_task() запускає dispatcher
    # як окрему asyncio Task.
    dispatcher_task = asyncio.create_task(
        dispatcher()
    )

    # =========================================================================
    # СТВОРЮЄМО TASK ДЛЯ GPS
    # =========================================================================

    # GPS працює паралельно з іншими компонентами.
    gps_task = asyncio.create_task(
        gps_system()
    )

    # =========================================================================
    # СТВОРЮЄМО TASK ДЛЯ MONITOR
    # =========================================================================

    # Монітор працює у фоні.
    monitor_task = asyncio.create_task(
        monitor()
    )

    # =========================================================================
    # СТВОРЮЄМО TASK ДЛЯ КУР'ЄРІВ
    # =========================================================================

    courier_tasks = []

    # Створюємо кілька кур'єрів.
    for i in range(1, COURIERS_COUNT + 1):

        task = asyncio.create_task(
            courier(f"Кур'єр-{i}")
        )

        courier_tasks.append(task)

    # =========================================================================
    # ОЧІКУЄМО DISPATCHER ТА GPS
    # =========================================================================

    # gather() дозволяє чекати
    # на кілька задач одночасно.
    #
    # Тут ми очікуємо:
    #
    #     dispatcher
    #     GPS
    #
    await asyncio.gather(
        dispatcher_task,
        gps_task
    )

    # =========================================================================
    # ЧЕКАЄМО ЗАВЕРШЕННЯ ВСІХ ЗАМОВЛЕНЬ
    # =========================================================================

    print()
    print("[Система] Очікую завершення всіх замовлень...")

    # Queue.join() чекає, поки кожне замовлення,
    # додане через queue.put(),
    # не буде позначене через queue.task_done().
    await orders_queue.join()

    print("[Система] Усі замовлення оброблено.")

    # =========================================================================
    # СКАСОВУЄМО КУР'ЄРІВ
    # =========================================================================

    # Кур'єри працюють у нескінченному циклі:
    #
    #     while True:
    #
    # Тому після завершення всіх замовлень
    # вони самі не завершаться.
    #
    # У цей момент вони просто чекатимуть:
    #
    #     await orders_queue.get()
    #
    # Тому ми скасовуємо їхні Task.
    print("[Система] Завершую роботу кур'єрів...")

    for task in courier_tasks:
        task.cancel()

    # =========================================================================
    # ЧЕКАЄМО ЗАВЕРШЕННЯ КУР'ЄРІВ
    # =========================================================================

    # return_exceptions=True потрібен тому,
    # що після cancel() виникає CancelledError.
    #
    # gather() збере результати завершення всіх Task,
    # не перериваючи програму через CancelledError.
    await asyncio.gather(
        *courier_tasks,
        return_exceptions=True
    )

    # =========================================================================
    # СКАСОВУЄМО MONITOR
    # =========================================================================

    print("[Система] Зупиняю монітор...")

    monitor_task.cancel()

    # Коректно очікуємо завершення монітора.
    await asyncio.gather(
        monitor_task,
        return_exceptions=True
    )

    # =========================================================================
    # ПІДСУМКОВА СТАТИСТИКА
    # =========================================================================

    print()
    print("=" * 70)
    print("             ДОСТАВКА ЗАВЕРШИЛА РОБОТУ")
    print("=" * 70)

    print(
        f"Отримано замовлень: "
        f"{len(all_orders)}"
    )

    print(
        f"Виконано замовлень: "
        f"{completed_orders}"
    )

    print(
        f"Не виконано: "
        f"{failed_orders}"
    )

    print(
        f"Загальна сума оплат: "
        f"{balance} ₾"
    )

    print()
    print("До побачення!")


