# MONITOR — ФОНОВИЙ МОНІТОР
# =============================================================================

async def monitor():
    """
    Фоновий монітор системи.

    Кожні 2 секунди він показує:
    - кількість замовлень у черзі;
    - поточний баланс;
    - кількість виконаних замовлень;
    - кількість невиконаних замовлень.
    """

    global balance

    try:

        while True:

            # Читаємо balance під захистом Lock.
            #
            # Це гарантує, що в момент читання
            # інша coroutine не змінює balance.
            async with balance_lock:
                current_balance = balance

            print()
            print("========== МОНІТОР ==========")

            print(
                f"Замовлень у черзі: "
                f"{orders_queue.qsize()}"
            )

            print(
                f"Баланс: "
                f"{current_balance} ₾"
            )

            print(
                f"Виконано: "
                f"{completed_orders}"
            )

            print(
                f"Не виконано: "
                f"{failed_orders}"
            )

            print("==============================")
            print()

            # Чекаємо 2 секунди.
            #
            # Використовуємо саме asyncio.sleep(),
            # а не time.sleep().
            #
            # asyncio.sleep() не блокує event loop.
            await asyncio.sleep(2)

    except asyncio.CancelledError:

        print("[Монітор] Монітор завершує роботу.")

        # Передаємо CancelledError далі.
        raise


