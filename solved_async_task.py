# DISPATCHER — СТВОРЮВАЧ ЗАМОВЛЕНЬ
# =============================================================================

async def dispatcher():
    """
    Dispatcher — Producer.

    Він створює нові замовлення
    та додає їх до asyncio.Queue.
    """

    # Список доступних страв.
    #
    # Кожен елемент:
    #
    #     (назва страви, ціна)
    foods = [
        ("Піца", 25),
        ("Бургер", 18),
        ("Суші", 32),
        ("Паста", 22),
        ("Салат", 15),
    ]

    print_separator()
    print("[Диспетчер] Починаю приймати замовлення.")
    print_separator()

    # Створюємо TOTAL_ORDERS замовлень.
    for order_id in range(1, TOTAL_ORDERS + 1):

        # Випадково вибираємо страву.
        food, price = random.choice(foods)

        # Створюємо словник із даними замовлення.
        order = {
            "id": order_id,
            "food": food,
            "price": price,
        }

        # Зберігаємо замовлення
        # для підсумкової статистики.
        all_orders.append(order)

        print(
            f"[Диспетчер] "
            f"Нове замовлення #{order_id}: "
            f"{food} — {price} ₾"
        )

        # Додаємо замовлення до Queue.
        #
        # Кур'єри зможуть отримати його
        # за допомогою:
        #
        #     await orders_queue.get()
        await orders_queue.put(order)

        # Невелика пауза між створенням замовлень.
        #
        # Поки dispatcher очікує,
        # інші coroutine продовжують працювати.
        await asyncio.sleep(
            random.uniform(0.2, 0.7)
        )

    print_separator()
    print("[Диспетчер] Усі замовлення прийнято.")
    print_separator()


