    await asyncio.sleep(1)

    print("[GPS] GPS ГОТОВИЙ!")

    # Встановлюємо Event.
    #
    # Усі coroutine, які виконують:
    #
    #     await gps_ready.wait()
    #
    # тепер зможуть продовжити роботу.
    gps_ready.set()


