# ОБРОБКА ОДНОГО ЗАМОВЛЕННЯ
# =============================================================================

async def process_order(order, courier_name):
    """
    Повний процес обробки одного замовлення:

        1. Отримання замовлення
        2. Перевірка оплати
        3. Приготування їжі
        4. Очікування GPS
        5. Доставка
        6. Оновлення статистики
    """

    global completed_orders
    global failed_orders

    order_id = order["id"]

    print_separator()

    print(
        f"[{courier_name}] "
        f"Отримав замовлення #{order_id}: "
        f"{order['food']}"
    )

    # =========================================================================
    # КРОК 1. ПЕРЕВІРКА ОПЛАТИ
    # =========================================================================

    payment_success = await process_payment(order)

    # Якщо оплата не пройшла,
    # замовлення далі обробляти не потрібно.
    if not payment_success:

        failed_orders += 1

        print(
            f"[{courier_name}] "
            f"Замовлення #{order_id}: "
            f"не вдалося обробити."
        )

        return

    # =========================================================================
    # КРОК 2. ПРИГОТУВАННЯ
    # =========================================================================

    await prepare_order(order)

    # =========================================================================
    # КРОК 3. ОЧІКУВАННЯ GPS
    # =========================================================================

    print(
        f"[{courier_name}] "
        f"Замовлення #{order_id}: "
        f"перевіряю GPS..."
    )

    # Якщо GPS ще не готовий,
    # coroutine призупиниться саме тут.
    #
    # При цьому event loop продовжить
    # виконувати інші задачі.
    await gps_ready.wait()

    print(
        f"[{courier_name}] "
        f"Замовлення #{order_id}: "
        f"GPS готовий."
    )

    # =========================================================================
    # КРОК 4. ДОСТАВКА З ОБМЕЖЕННЯМ ЧАСУ
    # =========================================================================

    try:

        # Кур'єр має максимум 5 секунд
        # для доставки замовлення.
        #
        # Якщо deliver_order() працюватиме довше,
        # wait_for() скасує її та виникне TimeoutError.
        await asyncio.wait_for(
            deliver_order(
                order,
                courier_name
            ),
            timeout=5
        )

        # Якщо доставка успішна,
        # збільшуємо кількість виконаних замовлень.
        completed_orders += 1

    except asyncio.TimeoutError:

        # Якщо кур'єр не встиг за 5 секунд,
        # замовлення вважаємо невиконаним.
        failed_orders += 1

        print(
            f"[{courier_name}] "
            f"Замовлення #{order_id}: "
            f"TIMEOUT! Доставка занадто довга."
        )


